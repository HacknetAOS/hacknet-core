#!/usr/bin/env python3
"""Compile design/layout.toml into every consumer of the grid.

Outputs:
  layout.json        runtime description for hacknetd / tests
  Geo.qml            Quickshell singleton (pragma Singleton)
  hacknet_layout.lua Hyprland geometry table

The rectangle math here is mirrored in daemon/crates/hacknet-proto/src/layout.rs.
`hacknet-layout --check` (and a Rust test) guards the two implementations
against drift.
"""
from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path

REQUIRED = ("gap", "topbar", "netmap", "sidebar", "terminal")


def tokens(raw: dict) -> dict:
    g = raw["grid"]
    missing = [k for k in REQUIRED if k not in g]
    if missing:
        raise SystemExit(f"layout.toml: missing [grid] keys: {', '.join(missing)}")
    compact = raw.get("breakpoints", {}).get("compact", {})
    return {
        "gap": g["gap"],
        "topbar": g["topbar"],
        "netmap": g["netmap"],
        "sidebar": g["sidebar"],
        "terminal": g["terminal"],
        "compact_max_width": compact.get("max_width", 0),
        "compact_sidebar": compact.get("sidebar", g["sidebar"]),
        "compact_terminal": compact.get("terminal", g["terminal"]),
        "compact_netmap": compact.get("netmap", g["netmap"]),
        "compact_visualizer": compact.get("visualizer", raw["visualizer"]["size"]),
    }


def rect(x: int, y: int, w: int, h: int) -> dict:
    return {"x": x, "y": y, "w": w, "h": h}


def compute(raw: dict, width: int, height: int) -> dict:
    t = tokens(raw)
    compact = t["compact_max_width"] > 0 and width <= t["compact_max_width"]
    sidebar = t["compact_sidebar"] if compact else t["sidebar"]
    terminal = t["compact_terminal"] if compact else t["terminal"]
    netmap = t["compact_netmap"] if compact else t["netmap"]
    topbar = t["topbar"]
    vis = t["compact_visualizer"] if compact else raw["visualizer"]["size"]

    stage_w = width - sidebar - terminal
    stage_h = height - topbar - netmap
    if stage_w <= 0 or stage_h <= 0:
        raise SystemExit(
            f"layout does not fit {width}x{height}: stage would be {stage_w}x{stage_h}"
        )

    pad = raw["visualizer"]["padding"]
    out = {
        "version": raw.get("version", 1),
        "screen": {"w": width, "h": height},
        "compact": compact,
        "tokens": {
            "gap": t["gap"],
            "topbar": topbar,
            "netmap": netmap,
            "sidebar": sidebar,
            "terminal": terminal,
            "visualizer": vis,
            "visualizer_padding": pad,
            "ram": raw["dock"]["ram"],
            "min_slot": raw["dock"]["min_slot"],
            "splitter": raw["dock"]["splitter"],
            "stage_border": raw["stage"]["border"],
            "stage_bracket": raw["stage"]["bracket"],
        },
        "rects": {
            "topbar": rect(0, 0, width, topbar),
            "sidebar": rect(0, topbar, sidebar, height - topbar - netmap),
            "visualizer": rect(pad, height - netmap - vis - pad, sidebar - 2 * pad, vis),
            "stage": rect(sidebar, topbar, stage_w, stage_h),
            "terminal": rect(width - terminal, topbar, terminal, height - topbar),
            "netmap": rect(0, height - netmap, width - terminal, netmap),
        },
    }
    return out


def qml(doc: dict) -> str:
    t, r = doc["tokens"], doc["rects"]
    s = doc["screen"]
    lines = [
        "// GENERATED by tools/hacknet-layout.py — do not edit.",
        "pragma Singleton",
        "import QtQuick",
        "",
        "QtObject {",
        f"    readonly property int screenWidth: {s['w']}",
        f"    readonly property int screenHeight: {s['h']}",
        f"    readonly property bool compact: {'true' if doc['compact'] else 'false'}",
        f"    readonly property int gap: {t['gap']}",
        f"    readonly property int topbarHeight: {t['topbar']}",
        f"    readonly property int netmapHeight: {t['netmap']}",
        f"    readonly property int sidebarWidth: {t['sidebar']}",
        f"    readonly property int terminalWidth: {t['terminal']}",
        f"    readonly property int visualizerSize: {t['visualizer']}",
        f"    readonly property int visualizerPadding: {t['visualizer_padding']}",
        f"    readonly property int ramHeight: {t['ram']}",
        f"    readonly property int minSlotHeight: {t['min_slot']}",
        f"    readonly property int splitter: {t['splitter']}",
        f"    readonly property int stageBorder: {t['stage_border']}",
        f"    readonly property int stageBracket: {t['stage_bracket']}",
    ]
    for name, rc in r.items():
        cap = name[0].upper() + name[1:]
        lines += [
            f"    readonly property int {name}X: {rc['x']}",
            f"    readonly property int {name}Y: {rc['y']}",
            f"    readonly property int {name}W: {rc['w']}",
            f"    readonly property int {name}H: {rc['h']}",
        ]
    lines.append("}")
    return "\n".join(lines) + "\n"


def lua(doc: dict) -> str:
    t, r = doc["tokens"], doc["rects"]
    s = doc["screen"]
    body = [
        "-- GENERATED by tools/hacknet-layout.py — do not edit.",
        "return {",
        f"  screen = {{ w = {s['w']}, h = {s['h']} }},",
        f"  blocks = {{",
        f"    topbar = {{ x = {r['topbar']['x']}, y = {r['topbar']['y']}, w = {r['topbar']['w']}, h = {r['topbar']['h']} }},",
        f"    sidebar = {{ x = {r['sidebar']['x']}, y = {r['sidebar']['y']}, w = {r['sidebar']['w']}, h = {r['sidebar']['h']} }},",
        f"    stage = {{ x = {r['stage']['x']}, y = {r['stage']['y']}, w = {r['stage']['w']}, h = {r['stage']['h']} }},",
        f"    terminal = {{ x = {r['terminal']['x']}, y = {r['terminal']['y']}, w = {r['terminal']['w']}, h = {r['terminal']['h']} }},",
        f"    netmap = {{ x = {r['netmap']['x']}, y = {r['netmap']['y']}, w = {r['netmap']['w']}, h = {r['netmap']['h']} }},",
        f"    visualizer = {{ x = {r['visualizer']['x']}, y = {r['visualizer']['y']}, w = {r['visualizer']['w']}, h = {r['visualizer']['h']} }},",
        "  },",
        f"  gap = {t['gap']},",
        f"  border = {t['stage_border']},",
        "}",
    ]
    return "\n".join(body) + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--layout", default="design/layout.toml")
    ap.add_argument("--out", default="build/layout")
    ap.add_argument("--width", type=int, default=0)
    ap.add_argument("--height", type=int, default=0)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    raw = tomllib.loads(Path(args.layout).read_text())
    w = args.width or raw["display"]["baseline_width"]
    h = args.height or raw["display"]["baseline_height"]

    min_w, min_h = raw["display"]["min_width"], raw["display"]["min_height"]
    if w < min_w or h < min_h:
        raise SystemExit(f"unsupported resolution {w}x{h} (minimum {min_w}x{min_h})")

    doc = compute(raw, w, h)
    if args.check:
        print(f"ok {w}x{h} compact={doc['compact']} stage={doc['rects']['stage']}")
        return 0

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    (out / "layout.json").write_text(json.dumps(doc, indent=2) + "\n")
    (out / "Geo.qml").write_text(qml(doc))
    (out / "hacknet_layout.lua").write_text(lua(doc))
    print(f"wrote {out}/layout.json {out}/Geo.qml {out}/hacknet_layout.lua")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
